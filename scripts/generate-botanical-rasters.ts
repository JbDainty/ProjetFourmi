import { species } from '../src/data/botany';
import { build } from 'esbuild';
import { chromium } from '@playwright/test';
import { mkdirSync, writeFileSync, unlinkSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';

async function main() {
  const require = createRequire(import.meta.url);
  const bundle = await build({
    entryPoints: ['scripts/botanical-raster-painter.tsx'],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'BotanicalCache',
    platform: 'browser',
    mainFields: ['browser', 'module', 'main'],
    define: { 'process.env.NODE_ENV': '"production"', __DEV__: 'false' },
    alias: {
      'react-native': 'react-native-web',
      'react-native-svg': require.resolve('react-native-svg/lib/module/elements.web.js'),
    },
    loader: { '.png': 'dataurl', '.webp': 'dataurl', '.ttf': 'dataurl' },
  });
  const browser = await chromium.launch({
    executablePath: '/usr/bin/chromium',
    args: ['--no-sandbox'],
  });
  const manifest: string[] = [];
  let bytes = 0;
  mkdirSync('assets/botanical', { recursive: true });
  try {
    const page = await browser.newPage();
    await page.setContent('<!doctype html><html><body></body></html>');
    await page.addScriptTag({ content: bundle.outputFiles[0].text });
    for (let index = 0; index < species.length; index++) {
      const stages: string[] = [];
      for (let stage = 0; stage <= 4; stage++) {
        const targetName = `plant-${String(index).padStart(2, '0')}-${stage}.${index < 20 ? 'png' : 'webp'}`;
        if (index < 20 && existsSync('assets/botanical/' + targetName)) {
          stages.push(`require('../../assets/botanical/${targetName}')`);
          continue;
        }
        const url = await page.evaluate(
          async ({ index, stage }) =>
            (
              window as unknown as {
                BotanicalCache: { paintBotanical: (i: number, s: number) => Promise<string> };
              }
            ).BotanicalCache.paintBotanical(index, stage),
          { index, stage },
        );
        const name = `plant-${String(index).padStart(2, '0')}-${stage}.${index < 20 ? 'png' : 'webp'}`;
        const png = Buffer.from(url.split(',')[1], 'base64');
        writeFileSync('assets/botanical/' + name, png);
        bytes += png.length;
        stages.push(`require('../../assets/botanical/${name}')`);
      }
      manifest.push(`  [${stages.join(', ')}]`);
      if (index % 10 === 0) console.log(`Cached through specimen ${index + 1}`);
      const old = `assets/botanical/plant-${String(index).padStart(2, '0')}-5.png`;
      if (existsSync(old)) unlinkSync(old);
    }
    writeFileSync(
      'src/data/botanicalRasters.ts',
      `/** Generated by npm run assets:botanical. Existing SVG art cached for native Image. */\nexport const botanicalRasters = [\n${manifest.join(',\n')}\n] as const;\n`,
    );
    console.log(
      `Cached 200 species × 5 watercolor stages (the seal is separate): ${(bytes / 1024 / 1024).toFixed(1)} MiB of compiled plate assets.`,
    );
  } finally {
    await browser.close();
  }
}
main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
